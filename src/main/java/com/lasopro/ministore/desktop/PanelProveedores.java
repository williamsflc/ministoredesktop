    private void btEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btEliminarActionPerformed
        
        int selected = tablaProveedores.getSelectedRow();
        if(selected < 0){
            JOptionPane.showMessageDialog(this, "Debe selecionar un proveedor para eliminarlo");
            return;
        }
        int res = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el proveedor con nombre '"+tablaProveedores.getValueAt(selected, 1)+"' ?", "Eliminar proveedor", JOptionPane.YES_NO_CANCEL_OPTION);
        if(res == JOptionPane.YES_OPTION){
            db.delete((Integer)tablaProveedores.getValueAt(selected, 0));
        }
        refresh();
        
    }//GEN-LAST:event_btEliminarActionPerformed

