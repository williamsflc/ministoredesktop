    private void jList1ValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jList1ValueChanged
        
        if(this.panelVenta1.isVentaEnCurso()){
            JOptionPane.showMessageDialog(this, "Hay una venta en curso, Finalice o Aborte la venta para poder visualizar", "Venta en curso", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if(jList1.getSelectedValue() == null){
            return;
        }
        
        MinistoreDesktop.runInThread("Cargando datos de venta seleccionada...", ()->{
            this.panelVenta1.mostrarVenta(jList1.getSelectedValue().info);
            this.lTituloVenta.setText(jList1.getSelectedValue().toString().replace("<br/>",""));
            this.panelVenta1.setVisible(true);
        });
    }//GEN-LAST:event_jList1ValueChanged

