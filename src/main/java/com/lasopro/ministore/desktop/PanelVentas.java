    public void llenarHistoricoVentas(){
        
        String mostrar = (String)cbMostrarHis.getSelectedItem();
        
        if(mostrar == null) mostrar = "Hoy";
        
        Calendar c = Calendar.getInstance();
        c.set(Calendar.HOUR_OF_DAY, 0);
        c.set(Calendar.MINUTE, 0);
        c.set(Calendar.SECOND, 0);
        c.set(Calendar.MILLISECOND, 0);
        List<Map<String,Object>> list;
        switch(mostrar){
            case "Hoy": 
                list = db.listByDate(new java.sql.Date(c.getTimeInMillis()));
                break;
            case "Últimos 7 días": 
                c.add(Calendar.DAY_OF_MONTH, -7);
                list = db.listByDate(new java.sql.Date(c.getTimeInMillis()));
                break;
            case "Últimos 30 días": 
                c.add(Calendar.DAY_OF_MONTH, -30);
                list = db.listByDate(new java.sql.Date(c.getTimeInMillis()));
                break;
            case "Últimos 6 meses": 
                c.add(Calendar.MONTH, -6);
                list = db.listByDate(new java.sql.Date(c.getTimeInMillis()));
                break;
            default:
                list = db.listByDate(new java.sql.Date(c.getTimeInMillis()));
                break;
        }
        
        DefaultListModel<Venta> model = new DefaultListModel<>();
        
        if(list.size() > 1000){
            JOptionPane.showMessageDialog(this, "Se encontraron "+list.size()+" ventas, se mostraran únicamente las últimas 1000.");
        }
        
        for(int i = 0; i < list.size() && i < 1000 ; i++){
            Map<String,Object> m = list.get(i);
            model.addElement(new Venta(m));
        }
        jList1.setModel(model);
        
    }
    
    
