    private void actualizarProveedor(int fila){
        try{
         System.out.println("Actualizando fila");
         Map<String, Object> info = new HashMap<>();
         info.put("id",        tablaProveedores.getModel().getValueAt(fila, 0));
         info.put("nombre",    tablaProveedores.getModel().getValueAt(fila, 1));
         info.put("telefono",  tablaProveedores.getModel().getValueAt(fila, 2));
         info.put("email",     tablaProveedores.getModel().getValueAt(fila, 3));
         info.put("direccion", tablaProveedores.getModel().getValueAt(fila, 4));
         db.update(info);
         refresh();
         }catch(Throwable err){
            JOptionPane.showMessageDialog(this, "Error al actualizar el proveedor: "+err.getMessage(), "Error al actualizar proveedor", JOptionPane.ERROR_MESSAGE);
            MinistoreDesktop.log.err("Error al actualizar el proveedor", err);
        }
         
    }
    
    
    @Override
    public final void refresh(){
        MinistoreDesktop.runInThread("Actualizando proveedores...", () -> {
            _refresh();
        });
    }

    public void _refresh(){
        String text = tBuscar.getText();

        PaginedResult pr;
        if(text.isBlank()){
            pr = db.list(1,10000);
        }else{
            pr = db.search(1, 10000, text);
        }

        DefaultTableModel model = (DefaultTableModel)tablaProveedores.getModel();
        for(int i=model.getRowCount()-1 ; i>=0 ; i--){
            model.removeRow(i);
        }

        for(Map<String,Object> p: pr.getData()){
            model.addRow(new Object[]{ p.get("id"), p.get("nombre"), p.get("telefono"), p.get("email"), p.get("direccion")  });
        }
    }
    
