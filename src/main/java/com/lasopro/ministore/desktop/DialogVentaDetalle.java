    private void bAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bAceptarActionPerformed
        
        info.put("cantidad", Double.valueOf(tCantidad.getText()));
        info.put("descuento", Double.valueOf(tDescuento.getText()));
        double cantidad = Double.parseDouble(tCantidad.getText());
        double precio = Double.parseDouble(tPrecio.getText());
        double descuento = Double.parseDouble(tDescuento.getText());
        info.put("total", cantidad * (precio - descuento));
        this.setVisible(false);
    }//GEN-LAST:event_bAceptarActionPerformed

