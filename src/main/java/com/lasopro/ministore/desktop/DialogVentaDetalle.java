    public static void mostrar(Map<String,Object> info, boolean editable){
        
        if(me == null){
            me = new DialogVentaDetalle(MinistoreDesktop.getMainFrame(), true);
        }
        
        
        me.tDescuento.setEditable(Resources.p("desc.x.venta.y.prod").equalsIgnoreCase("Habilitado"));
        
        
        me.info = info;
        
        Double precio    =  (Double)info.get("precio");
        Double descuento    =  (Double)info.get("descuento");
        descuento = descuento == null ? 0d : descuento;
        
        me.tCantidad.setText(info.get("cantidad")+"");
        me.tPrecio.setText(precio+"");
        me.tDescuento.setText(descuento+"");
        me.tPrecioConDescuento.setText((precio-descuento)+"");
        
        me.tCantidad.requestFocus();
        me.tCantidad.select(0, me.tCantidad.getText().length());
        
        me.lNombreProducto.setText("<html><p style='text-align:center'>"+info.get("codigo")+"<br/>"+info.get("nombre")+(info.get("descripcion") != null ? "<br/> ("+info.get("descripcion")+")":"")+"</p></html>");
        
        me.tCantidad.setEditable(editable);
        me.tDescuento.setEditable(editable && Resources.p("desc.x.venta.y.prod").equalsIgnoreCase("Habilitado"));
        me.bAceptar.setEnabled(editable);
        
        me.setVisible(true);
        
        
    }

